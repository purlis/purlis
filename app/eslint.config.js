import js from "@eslint/js";
import globals from "globals";
import reactHooks from "eslint-plugin-react-hooks";
import tseslint from "typescript-eslint";
import { purlisStories } from "./eslint.story-rules.js";
import { purlisUi, stillOff } from "./eslint.ui-rules.js";

/** The primitives libraries, which only their wrappers in `src/ui` import (#2904, ADR 0104):
 *  React Aria's, and the virtualizer a long list draws its rows in sight with (#5501). */
const PRIMITIVES = [
  "react-aria-components",
  "react-aria",
  "react-stately",
  "@tanstack/react-virtual",
];

export default tseslint.config(
  // `src/bindings.ts` and `src/uiRpc.ts` are generated by tauri-specta; a test in the app crate
  // guards each.
  { ignores: ["dist", "src-tauri", "src/bindings.ts", "src/uiRpc.ts"] },
  {
    files: ["**/*.{ts,tsx}"],
    extends: [
      js.configs.recommended,
      ...tseslint.configs.strict,
      reactHooks.configs.flat["recommended-latest"],
    ],
    languageOptions: { globals: globals.browser },
  },
  // The component layer (#2904, spec #2897): a screen draws a control from its family in
  // `src/ui`, and never imports the primitives library. Tests and stories draw what they test.
  {
    files: ["src/**/*.{ts,tsx}"],
    ignores: ["src/ui/**", "**/*.test.{ts,tsx}", "**/*.testkit.{ts,tsx}", "**/*.stories.tsx"],
    plugins: { purlis: purlisUi },
    rules: {
      "no-restricted-imports": [
        "error",
        {
          paths: PRIMITIVES.map((name) => ({
            name,
            message: "Screens draw from the component layer in `src/ui`, never the primitives.",
          })),
          patterns: PRIMITIVES.map((name) => ({
            group: [`${name}/*`],
            message: "Screens draw from the component layer in `src/ui`, never the primitives.",
          })),
        },
      ],
      // Every family's rule (`src/ui/<family>/lint.js`, #3387), an error. No raw `<button>` is
      // let through as another family's control any more (#2930): every family has moved.
      ...Object.fromEntries(Object.keys(purlisUi.rules).map((name) => [`purlis/${name}`, "error"])),
    },
  },
  // The stories' own lint (#3535, `eslint.story-rules.js`): what a `play` function must not
  // write, each rule an error.
  {
    files: ["**/*.stories.tsx"],
    plugins: { "purlis-stories": purlisStories },
    rules: Object.fromEntries(
      Object.keys(purlisStories.rules).map((name) => [`purlis-stories/${name}`, "error"]),
    ),
  },
  // **What each family's rule is still off in** (a family's `off`, in its `lint.js`), each
  // until the lane that moves it.
  ...stillOff,
);
