impl Class {
    /// Its name in an answer's span and in the slow log (FS-M1a, #7893).
    pub(crate) const fn name(self) -> &'static str {
        match self {
            Class::Window => "window",
            Class::Model => "model",
            Class::Git => "git",
            Class::Unmeasured => "unmeasured",
            Class::Uncounted => "uncounted",
        }
    }
}

/// The class `command` answers in ([`Class`]). A name the app does not register is
/// [`Class::Uncounted`]: nothing counts it. Looked up in a table made once, since every command
/// the window sends asks it on the main thread ([`crate::mainwatch::timed`]).
pub(crate) fn answer_class(command: &str) -> Class {
    static BY_NAME: std::sync::OnceLock<std::collections::HashMap<&str, Class>> =
        std::sync::OnceLock::new();
    BY_NAME
        .get_or_init(|| {
            ANSWER_CLASSES
                .iter()
                .flat_map(|(class, commands)| commands.iter().map(|command| (*command, *class)))
                .collect()
        })
        .get(command)
        .copied()
        .unwrap_or(Class::Uncounted)
}

/// A test's hold on the work a command hands off the window (#1949): while a gate named for the
/// work is closed, that work waits at its start on its blocking thread, so a test can see what
/// the window does in the meantime without a race against how fast the work is.
#[cfg(test)]
pub(crate) mod gate {
    use std::collections::HashMap;
    use std::sync::{Arc, Condvar, Mutex};

    /// One closed gate: open until [`Gate::open`] says so.
    #[derive(Default)]
    pub(crate) struct Gate {
        open: Mutex<bool>,
        opened: Condvar,
    }

    impl Gate {
        /// Waits until the gate is opened.
        pub(crate) fn wait(&self) {
            let mut open = self.open.lock().unwrap_or_else(|e| e.into_inner());
            while !*open {
                open = self.opened.wait(open).unwrap_or_else(|e| e.into_inner());
            }
        }

        /// Lets every work held at it go, and every one after it.
        pub(crate) fn open(&self) {
            *self.open.lock().unwrap_or_else(|e| e.into_inner()) = true;
            self.opened.notify_all();
        }
    }

    fn closed() -> &'static Mutex<HashMap<String, Arc<Gate>>> {
        static CLOSED: std::sync::OnceLock<Mutex<HashMap<String, Arc<Gate>>>> =
            std::sync::OnceLock::new();
        CLOSED.get_or_init(Mutex::default)
    }

    /// Closes the gate for the work named `what` until the answer is dropped, which opens it.
    pub(crate) fn close(what: &str) -> Closed {
        let gate = Arc::new(Gate::default());
        closed()
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .insert(what.to_owned(), Arc::clone(&gate));
        Closed {
            what: what.to_owned(),
            gate,
        }
    }

    /// The gate the work named `what` waits at, where one is closed.
    pub(crate) fn of(what: &str) -> Option<Arc<Gate>> {
        closed()
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .get(what)
            .cloned()
    }

    /// A gate a test closed: opened, and forgotten, when dropped.
    pub(crate) struct Closed {
        what: String,
        gate: Arc<Gate>,
    }

    impl Drop for Closed {
        fn drop(&mut self) {
            closed()
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .remove(&self.what);
            self.gate.open();
        }
    }
}

