import { useEffect, useState } from "react";
import vendored from "../icons/vendored.json";
// purlis's own licence and NOTICE, from the repository's root (`vite.config.ts`): the same two
// files every bundle carries beside the app (`tauri.conf.json`'s resources).
import { LICENSE, NOTICE } from "virtual:purlis-licence";

/** Each vendored directory's licence text, by the directory `vendored.json` names it by. */
const LICENCES: Record<string, string> = Object.fromEntries(
  Object.entries(
    import.meta.glob<string>("../icons/*/LICENSE", {
      query: "?raw",
      import: "default",
      eager: true,
    }),
  ).map(([path, text]) => [path.split("/").at(-2) ?? "", text]),
);

type ThirdParty = (typeof import("virtual:purlis-third-party"))["default"];
type ThirdPartyPackage = ThirdParty["packages"][number];

/** One package as a part of the notices names it, as the bundle's notices file does. */
function named(one: ThirdPartyPackage): string {
  const licence = one.licence ?? "no licence named";
  if (one.standard === undefined) return `${one.name} ${one.version} (${licence})`;
  const authors = one.authors?.length ? one.authors.join(", ") : "not named";
  return `${one.name} ${one.version} (${licence}; it ships no licence file, so this is the standard ${one.standard.join(" and ")} text; its authors: ${authors})`;
}

const counted = (n: number, one: string) => `${n} ${one}${n === 1 ? "" : "s"}`;

/**
 * **Every third-party crate and npm package the build ships, with its licence text** (#1784):
 * generated by `vite build` from the locked dependency graph (`tools/third-party-notices.mjs`),
 * the same notices the bundle carries as `THIRD-PARTY-NOTICES`. A lazy chunk, read only when the
 * licences are drawn, so no window pays for a megabyte of licence text at start. Each distinct
 * text is drawn once, under the packages that ship it.
 */
function ThirdPartyNotices() {
  const [notices, setNotices] = useState<ThirdParty | null>(null);
  useEffect(() => {
    let live = true;
    void import("virtual:purlis-third-party").then((module) => {
      if (live) setNotices(module.default);
    });
    return () => {
      live = false;
    };
  }, []);
  if (notices === null) return <p className="honest">Reading the third-party notices…</p>;
  if (!notices.generated)
    return (
      <p className="honest">
        This window was not built, so it has no third-party notices to list: a built purlis lists
        every crate and npm package it ships here.
      </p>
    );
  const crates = notices.packages.filter((one) => one.kind === "crate").length;
  return (
    <div data-testid="third-party-notices">
      <p className="honest">
        purlis is built with the {counted(crates, "Rust crate")} and{" "}
        {counted(notices.packages.length - crates, "npm package")} below, which others wrote. Each
        part names the packages that ship one licence text; open it for the text.
      </p>
      {notices.texts.map((text, at) => (
        <details key={at}>
          <summary>
            {notices.packages
              .filter((one) => one.texts.includes(at))
              .map(named)
              .join(", ")}
          </summary>
          <pre>{text}</pre>
        </details>
      ))}
    </div>
  );
}

/** The window event About sends to open the Licences tab in the project in front (#1719). */
export const OPEN_LICENCES = "purlis-open-licences";

/**
 * **Ask the window for the Licences tab** (#1719): About sits in the title bar, outside any
 * project, so the window opens it in the project in front. Answers whether one took the ask:
 * with no project open there is no strip to open a tab on, and About shows them in place.
 */
export function askLicencesTab(): boolean {
  return !window.dispatchEvent(new Event(OPEN_LICENCES, { cancelable: true }));
}

/** What the Licences tab is called. */
export const LICENCES_TITLE = "Licences";

/**
 * **purlis's own licence, and what it ships that others wrote, with their licences** (FM-3,
 * #1106): purlis's NOTICE and the Apache License 2.0 it is under first, then each vendored
 * asset (`app/icons/vendored.json`) and its licence text, compiled into the bundle so the
 * attribution travels with every copy of the app, then every third-party crate and npm package
 * the build ships (#1784). Drawn in a view tab of its own (#1719), and
 * in About where no project is open to hold the tab.
 */
export function Licences() {
  return (
    <>
      <div data-testid="own-licence">
        <p className="honest">purlis itself is under the Apache License 2.0, with this notice:</p>
        <pre>{NOTICE}</pre>
        <pre>{LICENSE}</pre>
      </div>
      {vendored.map((asset) => (
        <div key={asset.name}>
          <p className="honest">
            File and folder icons: {asset.name} {asset.version}, under the {asset.licence} licence,
            from {asset.source}.
          </p>
          <pre>{LICENCES[asset.files]}</pre>
        </div>
      ))}
      <ThirdPartyNotices />
    </>
  );
}

/** The Licences view tab (#1719). */
export function LicencesView() {
  return (
    <section className="licences" aria-label={LICENCES_TITLE} data-testid="licences-view">
      <Licences />
    </section>
  );
}
