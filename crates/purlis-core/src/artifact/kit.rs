//! **What a page's author is handed** (ADR 0122 §7, #5975): the page's port API as a TypeScript
//! declaration file, generated from the one catalogue ([`types`]), and a mock of the port that
//! answers from fixtures, so a page can be developed in any browser, outside purlis ([`MOCK`]).
//!
//! `purlis artifact types` prints the first and `purlis artifact mock` the second. Both are
//! kept in `crates/purlis-core/artifact-kit/`, inside the crate that compiles them in; the
//! app's typecheck reads the types from there (`app/artifact-kit/tsconfig.json`) and its unit
//! tests run the mock; a test here fails when the kept types are not what the catalogue
//! generates (`ARTIFACT_KIT_BLESS=1` writes them again).

use std::fmt::Write as _;

use serde_json::Value;

use crate::catalogue::{API, CATALOGUE, ErrorKind, PROTOCOL_KEY, Query};

/// **The mock of `purlis.port`**: a script a page loads before its own, outside purlis. It
/// steps aside when purlis's own port is there, so a page that still loads it in purlis talks
/// to purlis.
pub const MOCK: &str = include_str!("../../artifact-kit/purlis-page-mock.js");

/// The name the types are written under.
pub const TYPES_FILE: &str = "purlis-page.d.ts";

/// The name the mock is written under.
pub const MOCK_FILE: &str = "purlis-page-mock.js";

/// The file the mock reads its fixtures from, beside the page.
pub const FIXTURES_FILE: &str = "purlis-fixtures.json";

/// **`purlis-page.d.ts`**: the global `purlis`, what its port is asked, and what it answers,
/// each query's parameters and data typed from its JSON Schema, for every API version this
/// build answers.
pub fn types() -> String {
    let mut out = String::new();
    let kinds = ErrorKind::ALL
        .iter()
        .map(|k| format!("\"{}\"", k.as_str()))
        .collect::<Vec<_>>()
        .join(" | ");
    let _ = write!(
        out,
        "\
// Generated by `purlis artifact types` from purlis's query catalogue (ADR 0122 §7). Do not edit:
// generate it again when purlis moves.
//
// A page's script reaches purlis only through `purlis.port`. It declares what it reads in its
// index.html, and anything undeclared answers `not-approved`:
//
//   <script type=\"application/json\" id=\"purlis\">
//     {{ \"{PROTOCOL_KEY}\": {API}, \"data\": [\"data.json\"], \"queries\": {{ \"purlis.todo_list@1\": [\"done\"] }} }}
//   </script>
//
// `purlis artifact check <folder>` checks the declaration against the catalogue, and
// `purlis artifact mock` prints a port that answers from {FIXTURES_FILE}, for a page opened
// outside purlis.

declare namespace PurlisPage {{
  /** Why an answer has no data. */
  type ErrorKind = {kinds};

  /** Every answer: its data or why there is none (with a sentence for the reader, where purlis has one), when it was answered, and where its next page starts. */
  type Envelope<T> =
    | {{ data: T; at: string; cursor?: string; error?: never }}
    | {{ error: {{ kind: ErrorKind; message?: string }}; at: string; data?: never; cursor?: never }};

  /** What the port answers an ask with: its envelope and the ask's `id`, or `null` for an ask that was no ask. */
  type Answer<T = unknown> = Envelope<T> & {{ id: number | null }};

  /** Every query this purlis answers, as a page declares and asks it: `<id>@<N>`. */
  interface Queries {{
"
    );
    for api in 1..=API {
        for query in &CATALOGUE {
            entry(&mut out, query, api);
        }
    }
    let _ = write!(
        out,
        "  }}

  type QueryId = keyof Queries;

  /** One action a page offers: a row of purlis's action catalogue (`todo.done`) and its subject. */
  interface Offer {{
    does: string;
    subject: string;
  }}

  /** What the port is asked: a data file the page declared, a query it declared, or the whole set of actions it offers now (at most 8). */
  type Ask =
    | {{ id: number; read: string }}
    | {{ [K in QueryId]: {{ id: number; query: K; params?: Queries[K][\"params\"] | null }} }}[QueryId]
    | {{ id: number; offers: Offer[] }};

  /** What an offer set is answered: how many purlis took. */
  interface Offered {{
    offered: number;
  }}

  interface Port extends MessagePort {{
    postMessage(ask: Ask): void;
    onmessage: ((this: MessagePort, event: MessageEvent<Answer>) => void) | null;
  }}

  interface Page {{
    /** The API version purlis answers this page in. */
    readonly {PROTOCOL_KEY}: {API};
    readonly port: Port;
  }}

  /** One query's fixture: its envelope without `at`, which the mock answers with the time it answers. */
  type Fixture<T> = {{ data: T; cursor?: string }} | {{ error: {{ kind: ErrorKind; message?: string }} }};

  /** What the mock answers from, in {FIXTURES_FILE} beside the page. A data file with no fixture is fetched from the page's folder. */
  interface Fixtures {{
    data?: Record<string, unknown>;
    queries?: {{ [K in QueryId]?: Fixture<Queries[K][\"data\"]> }};
  }}
}}

/** purlis's port for this page: in purlis, purlis's own; outside it, the mock's. */
declare var purlis: PurlisPage.Page;
"
    );
    out
}

/// One query's entry of `Queries`: its description, parameters and data.
fn entry(out: &mut String, query: &Query, api: u32) {
    let mut doc = query.tool().description.to_owned();
    if let Some(old) = query.replaces {
        let _ = write!(doc, " Replaces {old}.");
    }
    if let Some(why) = query.deprecated {
        let _ = write!(doc, " Deprecated: {why}");
    }
    let _ = writeln!(out, "    /** {} */", comment(&doc));
    let _ = writeln!(out, "    \"{}@{api}\": {{", query.id());
    let _ = writeln!(out, "      params: {};", ts(&query.parameters(), 3));
    let _ = writeln!(out, "      data: {};", ts(&(query.result)(), 3));
    let _ = writeln!(out, "    }};");
}

/// `text` as it can stand in a `/** */` comment, on one line.
fn comment(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace("*/", "* /")
}

/// **The TypeScript type of `schema`**, the subset of JSON Schema the catalogue uses, at
/// nesting `depth` (two spaces each). Anything outside the subset is `unknown`, which a test
/// refuses for the core's catalogue, so a new shape is noticed.
fn ts(schema: &Value, depth: usize) -> String {
    if let Some(Value::Array(options)) = schema.get("enum") {
        let each: Vec<String> = options.iter().map(Value::to_string).collect();
        return each.join(" | ");
    }
    match schema.get("type") {
        Some(Value::Array(types)) => {
            let each: Vec<String> = types
                .iter()
                .map(|t| {
                    let mut one = schema.clone();
                    one["type"] = t.clone();
                    ts(&one, depth)
                })
                .collect();
            each.join(" | ")
        }
        Some(Value::String(t)) => match t.as_str() {
            "string" => "string".into(),
            "boolean" => "boolean".into(),
            "integer" | "number" => "number".into(),
            "null" => "null".into(),
            "array" => {
                let item = schema
                    .get("items")
                    .map_or("unknown".into(), |i| ts(i, depth));
                if item.contains(['|', '\n']) {
                    format!("Array<{item}>")
                } else {
                    format!("{item}[]")
                }
            }
            "object" => object(schema, depth),
            _ => "unknown".into(),
        },
        _ => "unknown".into(),
    }
}

fn object(schema: &Value, depth: usize) -> String {
    let Some(Value::Object(properties)) = schema.get("properties") else {
        return "Record<string, unknown>".into();
    };
    if properties.is_empty() {
        return "Record<string, never>".into();
    }
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = "  ".repeat(depth + 1);
    let mut out = String::from("{\n");
    for (name, property) in properties {
        if let Some(description) = property.get("description").and_then(Value::as_str) {
            let _ = writeln!(out, "{pad}/** {} */", comment(description));
        }
        let optional = if required.contains(&name.as_str()) {
            ""
        } else {
            "?"
        };
        let _ = writeln!(out, "{pad}{name}{optional}: {};", ts(property, depth + 1));
    }
    let _ = write!(out, "{}}}", "  ".repeat(depth));
    out
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    /// The types as `crates/purlis-core/artifact-kit/` keeps them, for the app's typecheck.
    const KEPT: &str = include_str!("../../artifact-kit/purlis-page.d.ts");

    #[test]
    fn the_kept_types_are_what_the_catalogue_generates() {
        let now = types();
        if std::env::var_os("ARTIFACT_KIT_BLESS").is_some() {
            let kept = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("artifact-kit")
                .join(TYPES_FILE);
            std::fs::write(kept, &now).unwrap();
            return;
        }
        assert!(
            KEPT == now,
            "crates/purlis-core/artifact-kit/{TYPES_FILE} is not what the catalogue generates: run \
             ARTIFACT_KIT_BLESS=1 cargo test -p purlis-core --lib artifact::kit and read its diff"
        );
    }

    #[test]
    fn every_query_is_typed_at_every_api_this_build_answers_with_nothing_left_unknown() {
        let types = types();
        for query in &CATALOGUE {
            for api in 1..=API {
                assert!(
                    types.contains(&format!("\"{}@{api}\": {{", query.id())),
                    "{} is typed @{api}",
                    query.id()
                );
            }
        }
        assert!(
            !types.contains("unknown;"),
            "no parameter or data of a core query is left unknown:\n{types}"
        );
        for kind in ErrorKind::ALL {
            assert!(types.contains(&format!("\"{}\"", kind.as_str())));
        }
    }

    #[test]
    fn a_schemas_required_fields_are_required_and_the_others_optional() {
        let schema = json!({
            "type": "object",
            "properties": {
                "file": { "type": "string", "description": "Its file." },
                "done": { "type": "boolean" },
                "rows": { "type": "array", "items": { "type": ["string", "null"] } },
                "how": { "enum": ["a", "b"] },
            },
            "required": ["file"],
        });
        assert_eq!(
            ts(&schema, 0),
            "{\n  /** Its file. */\n  file: string;\n  done?: boolean;\n  \
             rows?: Array<string | null>;\n  how?: \"a\" | \"b\";\n}"
        );
        assert_eq!(
            ts(&json!({ "type": "object", "properties": {} }), 0),
            "Record<string, never>"
        );
        assert_eq!(ts(&json!({ "type": "tuple" }), 0), "unknown");
    }

    #[test]
    fn a_description_cannot_close_its_comment() {
        assert_eq!(comment("Ends */ here\n and  on"), "Ends * / here and on");
    }

    #[test]
    fn the_mock_steps_aside_for_purliss_own_port_and_reads_its_fixtures_file() {
        assert!(
            MOCK.contains("if (Object.hasOwn(window, \"purlis\")"),
            "{MOCK}"
        );
        assert!(MOCK.contains(FIXTURES_FILE));
    }
}
