//! **Every first-party source file says whose it is and under what licence.**
//!
//! purlis is licensed under the Apache License 2.0, copyright Purlis. Each source file the
//! repository tracks starts with two lines in its language's comment syntax:
//!
//! ```text
//! // Copyright 2026 Purlis
//! // SPDX-License-Identifier: Apache-2.0
//! ```
//!
//! `//` for Rust, TypeScript and JavaScript, `/* … */` for CSS, and `#` for shell, Python, TOML
//! and YAML. A file whose first line is a shebang (`#!`) has them right after it.
//!
//! **What is scanned.** Every file under the repository with one of those extensions, and the
//! extensionless scripts in [`NAMED_SCRIPTS`], less the build outputs and installed packages in
//! [`NOT_SOURCE`] (what the `.gitignore` files leave out). The tree is walked rather than asked
//! of `git ls-files`, because cargo-mutants runs the tests in a copy with no `.git`. JSON cannot
//! hold a comment, and Markdown, HTML, SVG and the rest are not source, so they are not read.
//!
//! **What is not.** [`EXCLUDED`], each with its reason: generated files a test compares with
//! their generator's output, files purlis prints or copies byte for byte, fixtures and vendored
//! code. An entry that matches no tracked file fails, so the list cannot outlive what it names.

use std::path::{Path, PathBuf};

const COPYRIGHT: &str = "Copyright 2026 Purlis";
const SPDX: &str = "SPDX-License-Identifier: Apache-2.0";

/// Extensionless first-party scripts, read as shell.
const NAMED_SCRIPTS: &[&str] = &["tools/auditable-cargo"];

/// Paths (a trailing `/` covers a folder) that carry no header, and why.
#[rustfmt::skip]
const EXCLUDED: &[(&str, &str)] = &[
    ("app/src/bindings.ts",
     "generated by tauri-specta; a test compares it with the generator's output byte for byte"),
    ("app/src-tauri/plugin/opencode/purlis.ts",
     "the opencode shim, generated by purlis_core::opencode; a test compares the bundled copy \
      with the generator's output byte for byte"),
    ("app/src/uiRpc.ts",
     "generated by tauri-specta from the same commands; never edited by hand"),
    ("crates/unicode/src/tables.rs",
     "generated by tools/gen-unicode-tables.py from the Unicode data; regenerated, not edited"),
    ("crates/purlis-core/src/harness_declaration/",
     "the built-in harness declarations: `purlis harness show` prints each file verbatim \
      under its sha256 digest, so a header would change what it prints"),
    ("crates/purlis-core/templates/",
     "project templates, copied byte for byte into a new project; a published version never \
      changes (tests/it/project_templates.rs)"),
    ("tests/fixtures/",
     "recorded-behaviour fixtures: copied into every recorded scenario and compared byte for \
      byte (ADR 0046)"),
    ("fixtures/",
     "recorded corpora, compared byte for byte"),
    (".charter-scan-allow.toml",
     "the secret scan's allowlist: the commit guard lets only a commit made outside a chat \
      change it, so its header waits for the operator"),
    ("app/icons/",
     "vendored third-party assets, under their own licences"),
    ("operator/vendor/",
     "upstream agent-sandbox's release manifests, vendored verbatim under their own licence \
      (Apache-2.0); a test reads them as upstream published them"),
];

fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The header `path` must carry, or `None` when its kind of file is not source.
fn header(path: &str) -> Option<[String; 2]> {
    let ext = Path::new(path).extension().and_then(|e| e.to_str());
    let (open, close) = match ext {
        Some("rs" | "ts" | "tsx" | "js" | "mjs" | "cjs") => ("// ", ""),
        Some("css") => ("/* ", " */"),
        Some("sh" | "py" | "toml" | "yml" | "yaml") => ("# ", ""),
        None if NAMED_SCRIPTS.contains(&path) => ("# ", ""),
        _ => return None,
    };
    Some([COPYRIGHT, SPDX].map(|line| format!("{open}{line}{close}")))
}

fn excluded(path: &str) -> bool {
    EXCLUDED.iter().any(|(entry, _)| {
        if entry.ends_with('/') {
            path.starts_with(entry)
        } else {
            path == *entry
        }
    })
}

/// Folders that hold no source: build outputs, installed packages and tool state, by name
/// anywhere, or by path from the repository's root.
const NOT_SOURCE: &[&str] = &[
    ".git",
    "target",
    "node_modules",
    "dist",
    "dist-ssr",
    ".astro",
    "__pycache__",
    ".claude",
    ".idea",
    ".vscode",
    "app/src-tauri/gen",
    "app/src-tauri/permissions/autogenerated",
    "app/src-tauri/binaries",
    "app/src-tauri/extensions",
    "site/src/content/docs/docs",
];

/// Every file under the repository, as a path from its root, less [`NOT_SOURCE`].
fn tracked() -> Vec<String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        let mut entries: Vec<_> = std::fs::read_dir(dir)
            .expect("a readable folder")
            .map(|entry| entry.expect("an entry").path())
            .collect();
        entries.sort();
        for path in entries {
            let rel = path
                .strip_prefix(root)
                .expect("under the root")
                .to_string_lossy()
                .replace('\\', "/");
            let name = path.file_name().unwrap_or_default().to_string_lossy();
            let file_type = std::fs::symlink_metadata(&path)
                .expect("metadata")
                .file_type();
            if file_type.is_dir() {
                let skipped = NOT_SOURCE.contains(&rel.as_str())
                    || NOT_SOURCE.contains(&name.as_ref())
                    || name.starts_with("mutants.out");
                if !skipped {
                    walk(root, &path, out);
                }
            } else if file_type.is_file() {
                out.push(rel);
            }
        }
    }
    let root = repository();
    let mut out = Vec::new();
    walk(&root, &root, &mut out);
    out
}

/// Whether `text` starts with `header`, after a shebang line if it has one.
fn carries(text: &str, header: &[String; 2]) -> bool {
    let mut lines = text.lines().peekable();
    if lines.peek().is_some_and(|l| l.starts_with("#!")) {
        lines.next();
    }
    lines.next() == Some(header[0].as_str()) && lines.next() == Some(header[1].as_str())
}

#[test]
fn every_first_party_source_file_starts_with_its_copyright_and_spdx_lines() {
    purlis_core::unsteered!();
    let root = repository();
    let mut scanned = 0;
    let mut missing = Vec::new();
    for path in tracked() {
        let Some(header) = header(&path) else {
            continue;
        };
        if excluded(&path) {
            continue;
        }
        let text = std::fs::read_to_string(root.join(&path)).expect("a source file is text");
        scanned += 1;
        if !carries(&text, &header) {
            missing.push(path);
        }
    }
    // A scan that found nothing would pass on nothing.
    assert!(scanned > 1000, "only {scanned} source files were read");
    assert!(
        missing.is_empty(),
        "{} first-party source file(s) do not start with the two lines\n  {COPYRIGHT}\n  \
         {SPDX}\nin their comment syntax (after a shebang line, if any). Add them, or add the \
         file to EXCLUDED with its reason:\n{}",
        missing.len(),
        missing.join("\n")
    );
}

#[test]
fn every_exclusion_names_a_file_that_is_there() {
    purlis_core::unsteered!();
    let files = tracked();
    let stale: Vec<&str> = EXCLUDED
        .iter()
        .map(|(entry, _)| *entry)
        .chain(NAMED_SCRIPTS.iter().copied())
        .filter(|entry| {
            !files.iter().any(|path| {
                if entry.ends_with('/') {
                    path.starts_with(entry)
                } else {
                    path == entry
                }
            })
        })
        .collect();
    assert!(
        stale.is_empty(),
        "these entries match no tracked file; remove them: {stale:?}"
    );
}

#[test]
fn only_a_shebang_line_comes_before_the_header() {
    purlis_core::unsteered!();
    let rust = header("x.rs").expect("Rust is source");
    let shell = header("x.sh").expect("shell is source");
    let css = header("x.css").expect("CSS is source");
    assert_eq!(css[0], "/* Copyright 2026 Purlis */");
    assert!(carries(
        &format!("{}\n{}\n\nfn main() {{}}\n", rust[0], rust[1]),
        &rust
    ));
    assert!(carries(
        &format!("#!/bin/sh\n{}\n{}\n", shell[0], shell[1]),
        &shell
    ));
    assert!(!carries(
        &format!("// a comment first\n{}\n{}\n", rust[0], rust[1]),
        &rust
    ));
    assert!(!carries("fn main() {}\n", &rust));
    assert!(header("README.md").is_none() && header("app/package.json").is_none());
    assert!(header("tools/auditable-cargo").is_some());
    assert!(excluded("tests/fixtures/planes/minimal/charter.toml"));
    assert!(!excluded("crates/purlis-core/src/lib.rs"));
}
