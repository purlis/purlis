//! **purlis's one rule for a character a reader does not see, and its one mark** (SK-49, #3172).
//!
//! Three lists used to decide which characters are invisible: the core's, generated from
//! CPython for `charter/contain.py`'s `one_line`; the skill review's, written by hand; and the
//! hook's, written by hand again. Each missed something another held (the hand lists missed
//! the Arabic number signs, the Egyptian format controls and the blank spaces; the generated
//! one missed the variation selectors and the Hangul fillers), and each wrote what it found
//! its own way. This crate is the one answer, and a leaf, so the skills crate and the core
//! both ask it.
//!
//! - **Which characters**: [`invisible`], one table ([`tables::INVISIBLE`]) generated by
//!   `tools/gen-unicode-tables.py` from CPython's `unicodedata` and the UCD of the same
//!   Unicode version: general category `Cc`, `Cf`, `Cs`, `Zl` or `Zp`, any whitespace but the
//!   space, and every Default_Ignorable_Code_Point. No hand list.
//! - **Where, in context**: [`hidden`]. A joiner doing its one job inside a script or an
//!   emoji, and an emoji's presentation selector, read as text (ruling D-1301). Everything
//!   else the table names is hidden.
//! - **How it is shown**: [`marked`], each hidden character as `⟦U+XXXX⟧`.
//!
//! The crate also holds the other generated tables ([`tables`]): one generator writes one
//! file, so every table is of one Unicode version.

pub mod tables;

/// Is `ch` in one of `table`'s inclusive ranges?
///
/// A binary search: [`tables::NONPRINTABLE`] carries every unassigned codepoint and is
/// hundreds of ranges long, and it is asked once per character of every value purlis quotes.
/// The tables are sorted and disjoint by construction — the generator walks the codepoints in
/// order and closes a range the moment its predicate stops holding — which is the whole of
/// what the search needs.
pub fn in_table(ch: char, table: &[(u32, u32)]) -> bool {
    let cp = ch as u32;
    table
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                std::cmp::Ordering::Greater
            } else if cp > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Has `ch` no glyph a reader sees, or does it move the text around it? [`tables::INVISIBLE`].
///
/// One character on its own. A text is judged by [`hidden`], which lets a joiner doing its job
/// read as text; ask this only where a character stands alone or where nothing invisible is
/// allowed at all (a key, an email).
pub fn invisible(ch: char) -> bool {
    in_table(ch, &tables::INVISIBLE)
}

/// Does `ch` reorder the text around it (Bidi_Control: the overrides, embeddings, isolates and
/// marks)? Only to say what kind of invisible character something is; [`invisible`] decides
/// whether it is one.
pub fn bidi_control(ch: char) -> bool {
    in_table(ch, &tables::BIDI_CONTROL)
}

/// Does `ch` draw as nothing at all (Default_Ignorable_Code_Point: the joiners, the selectors,
/// the fillers, the tags)? Only to say what kind of invisible character something is.
pub fn default_ignorable(ch: char) -> bool {
    in_table(ch, &tables::DEFAULT_IGNORABLE)
}

/// What becomes of a line end (`\n`) and a tab in a text.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Breaks {
    /// They are the text's own layout and stay as they are: a file under review, a brief.
    Kept,
    /// They are marked like every other hidden character: one line of a report or a table
    /// cell, where a line end writes a second line and a tab shears every column after it.
    Marked,
}

/// Each character of `text` that a reader would not see there, in order.
///
/// Every character [`invisible`] names, except (ruling D-1301):
/// - a ZERO WIDTH JOINER between two emoji (after the first's presentation selector, if it has
///   one), as in a family or a rainbow flag;
/// - a ZERO WIDTH NON-JOINER between two letters of the Arabic script, as Persian writes it;
/// - either joiner after a letter or a virama of the Brahmic scripts (Devanagari to Malayalam)
///   and before a letter of them: a ZWJ asks for a half form, a ZWNJ keeps the virama shown;
/// - one presentation selector (VS15 or VS16) straight after an emoji, as in `❤️`;
/// - and, with [`Breaks::Kept`], a line end and a tab.
///
/// Each of those only changes how its neighbours are drawn: none can reorder text or hide a
/// word. Anywhere else (at either end, doubled, between Latin letters, a second selector, a
/// supplement selector) it is hidden like every other format character, since a run of
/// selectors after an emoji is exactly how text is smuggled behind one.
pub fn hidden(text: &str, breaks: Breaks) -> impl Iterator<Item = char> {
    flagged(text, breaks)
        .into_iter()
        .filter_map(|(ch, hidden)| hidden.then_some(ch))
}

/// Does `text` hold a character a reader would not see there ([`hidden`])?
pub fn hides(text: &str, breaks: Breaks) -> bool {
    hidden(text, breaks).next().is_some()
}

/// **`text` as a reader is shown it**: each character [`hidden`] names written as its mark,
/// `⟦U+XXXX⟧` (four hex digits at least, upper case), and the rest as itself.
///
/// The one mark everywhere: the install review, every terminal table, `one_line` and every
/// report built on it. A mark is not an escape a program reads back; it is there so nothing
/// the model or a terminal reads is hidden from the person. Marking is idempotent (a mark is
/// visible text), so a layer may mark what another layer already marked.
pub fn marked(text: &str, breaks: Breaks) -> String {
    let mut out = String::with_capacity(text.len());
    for (ch, hidden) in flagged(text, breaks) {
        if hidden {
            out.push_str(&format!("⟦U+{:04X}⟧", u32::from(ch)));
        } else {
            out.push(ch);
        }
    }
    out
}

/// Each character of `text`, with whether it is hidden there ([`hidden`]).
fn flagged(text: &str, breaks: Breaks) -> Vec<(char, bool)> {
    let chars: Vec<char> = text.chars().collect();
    (0..chars.len())
        .map(|at| {
            let ch = chars[at];
            let kept = breaks == Breaks::Kept && matches!(ch, '\n' | '\t');
            (ch, invisible(ch) && !kept && !does_its_job(&chars, at))
        })
        .collect()
}

/// ZERO WIDTH JOINER: joins two emoji into one, or asks a Brahmic consonant for its half form.
const ZWJ: char = '\u{200D}';
/// ZERO WIDTH NON-JOINER: keeps two letters of a joining script apart, as Persian spells a
/// word's parts (the prefix `mi` before a verb).
const ZWNJ: char = '\u{200C}';
/// VARIATION SELECTOR-15 and -16: an emoji drawn as text or as emoji.
const PRESENTATION: [char; 2] = ['\u{FE0E}', '\u{FE0F}'];

/// Is `chars[at]` a joiner or a presentation selector doing its one job between its
/// neighbours ([`hidden`])?
fn does_its_job(chars: &[char], at: usize) -> bool {
    let before = at.checked_sub(1).map(|i| chars[i]);
    let after = chars.get(at + 1).copied();
    let brahmic =
        before.is_some_and(|c| brahmic_letter(c) || virama(c)) && after.is_some_and(brahmic_letter);
    match chars[at] {
        ZWJ => {
            let emoji_before = match before {
                Some(selector) if PRESENTATION.contains(&selector) => {
                    at.checked_sub(2).is_some_and(|i| pictographic(chars[i]))
                }
                Some(before) => pictographic(before),
                None => false,
            };
            (emoji_before && after.is_some_and(pictographic)) || brahmic
        }
        ZWNJ => (before.is_some_and(arabic_letter) && after.is_some_and(arabic_letter)) || brahmic,
        selector if PRESENTATION.contains(&selector) => before.is_some_and(pictographic),
        _ => false,
    }
}

/// Is `c` a letter of the Brahmic scripts' blocks, Devanagari to Malayalam (U+0900-U+0D7F): a
/// consonant, a vowel or a vowel sign, never a digit or a danda.
fn brahmic_letter(c: char) -> bool {
    c.is_alphabetic() && matches!(c as u32, 0x0900..=0x0D7F)
}

/// Is `c` a virama of those scripts: each block's U+0x4D, and Malayalam's vertical-bar and
/// circular viramas.
fn virama(c: char) -> bool {
    let cp = c as u32;
    matches!(cp, 0x0900..=0x0D7F) && (cp & 0x7F == 0x4D || matches!(cp, 0x0D3B | 0x0D3C))
}

/// Is `c` an emoji a ZWJ sequence is made of: the pictographic blocks (symbols, dingbats,
/// arrows and the emoji planes) and the skin-tone modifiers in them. A close reading of
/// Unicode's Extended_Pictographic, without a table of its own.
fn pictographic(c: char) -> bool {
    matches!(
        c as u32,
        0x2300..=0x23FF | 0x2600..=0x27BF | 0x2B00..=0x2BFF | 0x1F000..=0x1FAFF
    )
}

/// Is `c` a letter of the Arabic script, in which Persian, Urdu and others are written: the
/// Arabic blocks and their presentation forms.
fn arabic_letter(c: char) -> bool {
    c.is_alphabetic()
        && matches!(
            c as u32,
            0x0600..=0x06FF | 0x0750..=0x077F | 0x08A0..=0x08FF | 0xFB50..=0xFDFF | 0xFE70..=0xFEFF
        )
}

