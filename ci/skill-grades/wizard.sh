REPO="purlis/purlis"
ENVIRONMENT="skill-grades"
WORKSPACE="purlis-skill-grades"

# gh_ready: gh installed and logged in, or say how and stop.
gh_ready() {
  if ! command -v gh >/dev/null 2>&1 || ! gh auth status >/dev/null 2>&1; then
    warn "gh is not installed or not logged in: run \`gh auth login\`, then this wizard again."
    exit 1
  fi
}

run_wizard() {

TOTAL_STAGES=5

banner "The CI grader's key: the skill-grades environment"

stage "Anthropic Console: a workspace of its own"
say "The key lives in a Console workspace used for nothing else, so its spend limit bounds"
say "exactly what skill grading can cost."
open_url "https://console.anthropic.com/settings/workspaces"
step "Create a workspace named $WORKSPACE (Settings → Workspaces → Create workspace)."
note "If the page has moved, look for Workspaces under the organization's settings."
pause "Press Enter once the workspace exists."

stage "Anthropic Console: the spend limit"
say "Set a monthly spend limit on $WORKSPACE. Grading stops when it is reached."
note "A pull request touching purlis-secrets runs its 48 trigger tests 3 times among the crowd"
note "and 3 times bare: 288 short runs. Each run's cost is in the grade's records"
note "(the result line's total_cost_usd), so the first grade tells you what one costs."
step "Open the workspace, find its limits, and set the monthly spend limit."
ask SPEND_LIMIT "The monthly limit you set, in USD (for the summary only):"
confirm "Is the spend limit on $WORKSPACE saved at \$$SPEND_LIMIT?" || {
  warn "Set the limit first: without it grading has no bound. Run the wizard again after."
  exit 1
}

stage "Anthropic Console: the key"
open_url "https://console.anthropic.com/settings/keys"
step "Create a key, choosing the workspace $WORKSPACE, named purlis-skill-grades-ci."
step "Copy it. It is shown once."
ask_secret ANTHROPIC_API_KEY "Paste the key (hidden):"
[[ -n "$ANTHROPIC_API_KEY" ]] || { warn "No key pasted; nothing was changed."; exit 1; }

stage "GitHub: the environment"
gh_ready
say "Creates the environment $ENVIRONMENT on $REPO. It needs no deployment-branch rule:"
say "a pull request's grade runs in it, a fork's pull request is never handed its secret,"
say "and the spend limit is what bounds the bill."
if confirm "Create or keep the environment $ENVIRONMENT on $REPO?"; then
  if gh api --method PUT "repos/$REPO/environments/$ENVIRONMENT" >/dev/null; then
    printf '  %s✓ ready%s environment %s\n' "$GREEN" "$RESET" "$ENVIRONMENT"
  else
    warn "GitHub refused; you need admin on $REPO."
    exit 1
  fi
else
  SKIPPED+=("the environment $ENVIRONMENT on $REPO")
fi

stage "GitHub: the key in the environment"
say "Stores the key as the environment's secret ANTHROPIC_API_KEY, the one name"
say ".github/workflows/skill-grades.yml reads. It goes to gh on stdin, never an argument."
if confirm "Store the key in $ENVIRONMENT now?"; then
  if printf '%s' "$ANTHROPIC_API_KEY" | gh secret set ANTHROPIC_API_KEY --env "$ENVIRONMENT" --repo "$REPO" >/dev/null; then
    WRITTEN_SECRET+=("ANTHROPIC_API_KEY (environment $ENVIRONMENT)")
    printf '  %s✓ set%s ANTHROPIC_API_KEY in %s\n' "$GREEN" "$RESET" "$ENVIRONMENT"
  else
    SKIPPED+=("ANTHROPIC_API_KEY in $ENVIRONMENT: gh secret set ANTHROPIC_API_KEY --env $ENVIRONMENT --repo $REPO")
  fi
else
  SKIPPED+=("ANTHROPIC_API_KEY in $ENVIRONMENT: gh secret set ANTHROPIC_API_KEY --env $ENVIRONMENT --repo $REPO")
fi
unset ANTHROPIC_API_KEY

finish
note "Spend limit: \$$SPEND_LIMIT a month on the Console workspace $WORKSPACE."
note "The next pull request that touches a built-in with trigger tests is graded;"
note "or run it by hand: gh workflow run skill-grades.yml --repo $REPO"
printf '\n'
}

run_wizard "$@"; exit
